<?php
defined( 'ABSPATH' ) || exit;

/**
 * Turns off other sitemap generators while ours is on, and reports what else could interfere.
 */
class IDXB_SEO_Conflicts {

	public static function init() {
		add_action( 'plugins_loaded', array( __CLASS__, 'take_over' ), 1 );
	}

	public static function take_over() {
		$s = IDXB_SEO_Settings::get()['sitemap'];
		if ( ! $s['enabled'] || ! $s['takeOver'] ) {
			return;
		}
		// WordPress core sitemaps (/wp-sitemap.xml).
		add_filter( 'wp_sitemaps_enabled', '__return_false' );
		// Yoast SEO: report the XML sitemap feature as off (non-destructive, reverts when our plugin is off).
		add_filter(
			'option_wpseo',
			function ( $o ) {
				if ( is_array( $o ) ) {
					$o['enable_xml_sitemap'] = false;
				}
				return $o;
			}
		);
		// Rank Math: drop the sitemap module.
		add_filter(
			'option_rank_math_modules',
			function ( $m ) {
				return is_array( $m ) ? array_values( array_diff( $m, array( 'sitemap' ) ) ) : $m;
			}
		);
	}

	/** Names of active SEO plugins (for the module activation screen). */
	public static function detect_plugins(): array {
		$map = array(
			'Yoast SEO'      => defined( 'WPSEO_VERSION' ),
			'Rank Math'      => class_exists( 'RankMath' ),
			'SEOPress'       => defined( 'SEOPRESS_VERSION' ),
			'All in One SEO' => defined( 'AIOSEO_VERSION' ),
		);
		return array_keys( array_filter( $map ) );
	}

	public static function detect(): array {
		$out = array();
		$s   = IDXB_SEO_Settings::get()['sitemap'];
		$on  = $s['enabled'] && $s['takeOver'];
		// name => [ active, handled automatically ]
		$map = array(
			'Yoast SEO'      => array( defined( 'WPSEO_VERSION' ), true ),
			'Rank Math'      => array( class_exists( 'RankMath' ), true ),
			'SEOPress'       => array( defined( 'SEOPRESS_VERSION' ), false ),
			'All in One SEO' => array( defined( 'AIOSEO_VERSION' ), false ),
			'Google XML Sitemaps' => array( class_exists( 'GoogleSitemapGeneratorLoader' ), false ),
		);
		foreach ( $map as $name => list( $active, $handled ) ) {
			if ( ! $active ) {
				continue;
			}
			if ( ! $handled ) {
				$out[] = array( 'plugin' => $name, 'level' => 'warn', 'msg' => sprintf( __( '%s is active and may generate its own sitemaps. Turn them off in its settings to avoid duplicates.', 'idxboost-seo' ), $name ) );
				continue;
			}
			$out[] = array(
				'plugin' => $name,
				'level'  => $on ? 'info' : 'warn',
				'msg'    => $on
					? sprintf( __( '%s is active: its XML sitemaps are turned off while IDXBoost SEO manages them. Its noindex/canonical settings are respected. Its robots.txt is replaced by this one.', 'idxboost-seo' ), $name )
					: sprintf( __( '%s is active and may serve the same /sitemap_index.xml. Turn on "Replace other plugins sitemaps" or turn its sitemaps off.', 'idxboost-seo' ), $name ),
			);
		}
		foreach ( array( 'sitemap.xml', 'sitemap_index.xml' ) as $f ) {
			if ( file_exists( dirname( IDXB_SEO_Robots::file_path() ) . '/' . $f ) ) {
				$out[] = array( 'plugin' => $f, 'level' => 'error', 'msg' => sprintf( __( 'There is a physical /%s file in the site root: the server serves it before WordPress. Delete it so the dynamic sitemap is used.', 'idxboost-seo' ), $f ) );
			}
		}
		if ( '' === (string) get_option( 'permalink_structure' ) ) {
			$out[] = array( 'plugin' => 'permalinks', 'level' => 'error', 'msg' => __( 'Permalinks are set to "Plain": /sitemap_index.xml requests never reach WordPress. Change them in Settings > Permalinks.', 'idxboost-seo' ) );
		}
		return $out;
	}

	/** Loopback check of the sitemap index. */
	public static function probe_sitemap(): array {
		$res = wp_remote_get( add_query_arg( 'idxb_probe', time(), home_url( '/sitemap_index.xml' ) ), array( 'timeout' => 10, 'sslverify' => false, 'redirection' => 0 ) );
		if ( is_wp_error( $res ) ) {
			return array( 'ok' => false, 'code' => 0, 'msg' => $res->get_error_message() );
		}
		$code = (int) wp_remote_retrieve_response_code( $res );
		$body = (string) wp_remote_retrieve_body( $res );
		$ours = str_contains( $body, 'generated by IDXBoost SEO' );
		$msg  = $ours ? __( 'The index responds and is generated by IDXBoost SEO.', 'idxboost-seo' ) : ( 200 === $code ? __( 'It responds, but something else generates it (static file or cache?).', 'idxboost-seo' ) : sprintf( __( 'It returned HTTP %d: the request does not reach WordPress (check the server/Nginx rules).', 'idxboost-seo' ), $code ) );
		return array( 'ok' => 200 === $code && $ours, 'code' => $code, 'msg' => $msg );
	}
}
